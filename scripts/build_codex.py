#!/usr/bin/env python3
"""Build static, lazy public records and a deferred section search index. No network or raw sources."""
import hashlib, html, json, re, shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
CONTENT=ROOT/'content'; OUT=ROOT/'site/data'
def compact(value):return json.dumps(value,ensure_ascii=False,separators=(',',':'))
def plain(value):return html.unescape(re.sub('<[^>]*>',' ',value or ''))
def norm(value):
 import unicodedata
 s=''.join(c for c in unicodedata.normalize('NFKD',value) if not unicodedata.combining(c)).lower().replace('’','').replace("'",'')
 return ' '.join(''.join(c if c.isalnum() else ' ' for c in s).split())
def build():
 world=json.loads((CONTENT/'reference/world.json').read_text())
 records=[json.loads(p.read_text()) for p in sorted((CONTENT/'records').glob('*.json'))]
 ids=[r['id'] for r in records]
 assert len(ids)==len(set(ids)), 'Duplicate article identity'
 OUT.mkdir(exist_ok=True);(OUT/'records').mkdir(exist_ok=True);(OUT/'supplements').mkdir(exist_ok=True)
 catalog={k:v for k,v in world.items() if k not in {'bodyChecksums','windowData','questTimelineAdditions','questPlayerAdditions','npcDiscoveries','relationshipMaps'}}
 # Preserve the established article order in navigation/related results.
 order=world.get('articleOrder',ids); records.sort(key=lambda r:order.index(r['id']) if r['id'] in order else len(order))
 catalog['articles']=[]; search={}; generated=set(); total=0
 catalog['imageDimensions']=json.loads((CONTENT/'reference/image-dimensions.json').read_text())
 people={p['article']:p for p in world['archiveIndex']['characters']+world['archiveIndex']['npcs']}
 for r in records:
  assert re.fullmatch('[a-z0-9-]+',r['id']),r['id']
  if r['protected']:assert not r.get('body'), 'Protected body in public content: '+r['id']
  body=r.get('body','')
  payload={k:r[k] for k in ['body','sections','brief','sources','relationshipMap','profile'] if k in r}
  
  for section in payload.get('sections',[]):
   evidence=section['evidence']; evidence['sources']=[payload.get('sources',[]).index(source) if source in payload.get('sources',[]) else source for source in evidence.get('sources',[])]
  encoded=compact(payload); digest=hashlib.sha256(encoded.encode()).hexdigest()[:16]
  name=r['id']+'.'+digest+'.json';generated.add(name);(OUT/'records'/name).write_text(encoded+'\n');total+=len(encoded.encode())
  meta={k:v for k,v in r.items() if k not in {'body','sections','sources','brief','relationshipMap','profile','sourceReview'}}
  meta.update(body='',bodyLoaded=False,bodyUrl='data/records/'+name,sectionCount=len(r.get('sections',[])))
  catalog['articles'].append(meta)
  matches=list(re.finditer(r'<h2\b([^>]*)>(.*?)</h2>',body,re.S)); sections=[]
  lead=body[:matches[0].start()] if matches else body
  sections.append({'id':'','title':'Overview','text':plain(lead)})
  for i,m in enumerate(matches):
   section=r.get('sections',[])[i] if i<len(r.get('sections',[])) else {}
   part=body[m.end():matches[i+1].start() if i+1<len(matches) else len(body)]
   sections.append({'id':section.get('id',''),'title':plain(m[2]),'text':plain(part)})
  if not r['protected']:search[r['id']]={'sections':sections}
 # Remove stale body versions so unreferenced old material is not shipped.
 for p in (OUT/'records').glob('*.json'):
  if p.name not in generated:p.unlink()
 for links in catalog['subchannelMap'].values():
  for link in links:link.pop('summary',None)
 # Registry and large personal-note index load only when that surface is opened.
 windows=world['windowData']; catalog['windowData']={k:v for k,v in windows.items() if k=='FENUMION_CHARACTER_BACKGROUNDS'}
 for name,key in [('player-perspectives','FENUMION_PLAYER_PERSPECTIVES'),('npc-discoveries','FENUMION_NPC_DISCOVERIES')]:
  (OUT/'supplements'/f'{name}.json').write_text(compact({key:windows[key]})+'\n')
 searchEncoded=compact(search); searchHash=hashlib.sha256(searchEncoded.encode()).hexdigest()[:16]
 searchName='search.'+searchHash+'.json';(OUT/searchName).write_text(searchEncoded+'\n');catalog['searchUrl']='data/'+searchName
 for p in OUT.glob('search.*.json'):
  if p.name!=searchName:p.unlink()
 catalog['consequenceChains']=json.loads((CONTENT/'reference/consequences.json').read_text())
 catalog['buildId']=hashlib.sha256(compact(catalog).encode()).hexdigest()[:16]
 (OUT/'catalog.js').write_text('// Generated by scripts/build_codex.py. Edit content/records, then rebuild.\nwindow.FENUMION_CATALOG='+compact(catalog)+';\nObject.assign(window,window.FENUMION_CATALOG.windowData);\n')
 print(f'Built {len(records)} canonical records; catalog {(OUT/"catalog.js").stat().st_size:,} bytes; lazy bodies {total:,} bytes; search {len(searchEncoded.encode()):,} bytes (deferred).')
if __name__=='__main__':build()
